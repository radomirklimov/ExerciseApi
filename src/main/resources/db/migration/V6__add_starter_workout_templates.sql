WHERE NOT EXISTS (SELECT 1 FROM workout WHERE name = 'Full Body Dumbbells' AND starter = TRUE);

INSERT INTO workout_exercise (workout_id, exercise_id, order_index)
SELECT w.workout_id, e.exercise_id, (e.rn - 1)::int
FROM workout w
JOIN (
    SELECT exercise_id, ROW_NUMBER() OVER (ORDER BY exercise_id) AS rn
    FROM exercise
    ORDER BY exercise_id
    LIMIT 8
) e ON TRUE
WHERE w.name = 'Upper Body Strength'
  AND w.starter = TRUE
  AND NOT EXISTS (SELECT 1 FROM workout_exercise we WHERE we.workout_id = w.workout_id);

INSERT INTO workout_exercise (workout_id, exercise_id, order_index)
SELECT w.workout_id, e.exercise_id, (e.rn - 1)::int
FROM workout w
JOIN (
    SELECT exercise_id, ROW_NUMBER() OVER (ORDER BY exercise_id) AS rn
    FROM exercise
    ORDER BY exercise_id
    OFFSET 8
    LIMIT 10
) e ON TRUE
WHERE w.name = 'Full Body Dumbbells'
  AND w.starter = TRUE
  AND NOT EXISTS (SELECT 1 FROM workout_exercise we WHERE we.workout_id = w.workout_id);