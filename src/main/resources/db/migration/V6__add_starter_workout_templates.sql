-- V6: starter workout templates. Reuses the existing exercise model;
-- a starter workout is a regular workout flagged as a starter template.

CREATE TABLE IF NOT EXISTS workout (
    workout_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    starter BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS workout_exercise (
    workout_exercise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id BIGINT NOT NULL,
    exercise_id BIGINT NOT NULL,
    order_index INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_workout_exercise_workout_id_exercise_id UNIQUE (workout_id, exercise_id),
    CONSTRAINT fk_workout_exercise_workout FOREIGN KEY (workout_id) REFERENCES workout (workout_id) ON DELETE CASCADE,
    CONSTRAINT fk_workout_exercise_exercise FOREIGN KEY (exercise_id) REFERENCES exercise (exercise_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_workout_exercise_workout_id ON workout_exercise (workout_id);
CREATE INDEX IF NOT EXISTS idx_workout_exercise_exercise_id ON workout_exercise (exercise_id);
CREATE INDEX IF NOT EXISTS idx_workout_starter ON workout (starter);

-- Idempotent seed of starter templates (only when matching exercises exist).
